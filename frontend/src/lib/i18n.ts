/**
 * Lightweight i18n for HostWise.
 *
 * The app's UI chrome and key surfaces are translated by the `t()` function,
 * which is driven by the `language` setting. Formatting (dates/numbers/currency)
 * is handled separately in `lib/utils.ts` via the same language setting.
 */

import { useSettings } from "@/contexts/settings-context";

export const LANGUAGES = ["English", "Français", "Español", "العربية", "Deutsch"] as const;
export type Language = (typeof LANGUAGES)[number];
export type LangCode = "en" | "fr" | "es" | "ar" | "de";

export function languageToCode(lang?: string | null): LangCode {
  switch ((lang || "English").trim()) {
    case "Français":
      return "fr";
    case "Español":
      return "es";
    case "العربية":
      return "ar";
    case "Deutsch":
      return "de";
    default:
      return "en";
  }
}

