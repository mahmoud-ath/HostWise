const TRANSLATIONS: Record<LangCode, Dict> = { en, fr, es, ar, de };

/** Translate a key for the given language (falls back to English). */
export function translate(key: string, lang?: string | null): string {
  const code = languageToCode(lang);
  return TRANSLATIONS[code][key] ?? TRANSLATIONS.en[key] ?? key;
}

/** Substitute `{placeholder}` tokens in a translated string. */
export function translateWith(key: string, vars: Record<string, string | number>, lang?: string | null): string {
  let out = translate(key, lang);
  for (const [k, v] of Object.entries(vars)) {
    out = out.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
  }
  return out;
}

/**
 * React hook — returns `t(key)` and `tWith(key, vars)` bound to the
 * active `language` setting.
 */
export function useI18n() {
  // Uses the *committed* language so the UI text only switches after Save.
  const { settings } = useSettings();
  const language = settings.language ?? "English";
  return {
    language,
    t: (key: string) => translate(key, language),
    tWith: (key: string, vars: Record<string, string | number>) => translateWith(key, vars, language),
  };
}
